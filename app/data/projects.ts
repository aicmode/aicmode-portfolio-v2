/** Filter order for the archive tabs. */
const CATEGORY_ORDER: readonly Category[] = [
  'AI Systems',
  'Automation',
  'Web Applications',
  'Websites',
  'Landing Pages',
  'EC',
]

/**
 * Only categories that actually have work in them become tabs — an empty tab
 * reads as a gap in the portfolio rather than as a filter.
 */
export const archiveCategories = CATEGORY_ORDER.filter((category) =>
  projects.some((project) => project.group === category),
)

export const projectCountByCategory = Object.fromEntries(
  archiveCategories.map((category) => [
    category,
    projects.filter((project) => project.group === category).length,
  ]),
) as Record<Category, number>
