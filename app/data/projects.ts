/** Selected Works: the eight highest-priority pieces for a first read. */
export const selectedProjects = projects
  .filter((project) => project.featured)
  .slice()
  .sort((a, b) => a.order - b.order)

export const archiveProjects = projects.slice().sort((a, b) => a.order - b.order)

/** Filter order for the archive tabs. */
const CATEGORY_ORDER: readonly Category[] = [
  'AI Systems',
  'Automation',
  'Web Applications',
  'Websites',
  'Landing Pages',
  'EC',
]

/**
 * Only categories that actually have work in them become tabs — an empty tab
 * reads as a gap in the portfolio rather than as a filter.
 */
export const archiveCategories = CATEGORY_ORDER.filter((category) =>
  projects.some((project) => project.group === category),
)

export const projectCountByCategory = Object.fromEntries(
  archiveCategories.map((category) => [
    category,
    projects.filter((project) => project.group === category).length,
  ]),
) as Record<Category, number>

/**
 * The archive's top level: AI・業務自動化 first, Web制作 second, and only
 * domains that actually hold work. Derived from the same `group` every card
 * already carries, so a project can never appear under a domain tab whose count
 * does not include it.
 */
export const archiveDomains = DOMAIN_ORDER.filter((domain) =>
  projects.some((project) => CATEGORY_DOMAIN[project.group] === domain),
)

const categoriesIn = (domain: Domain) =>
  archiveCategories.filter((category) => CATEGORY_DOMAIN[category] === domain)

/** The sub-categories offered inside one domain, in the existing tab order. */
export const categoriesByDomain: Record<Domain, readonly Category[]> = {
  'AI & Automation': categoriesIn('AI & Automation'),
  'Web Production': categoriesIn('Web Production'),
}

export const projectCountByDomain = Object.fromEntries(
  DOMAIN_ORDER.map((domain) => [
    domain,
    projects.filter((project) => CATEGORY_DOMAIN[project.group] === domain).length,
  ]),
) as Record<Domain, number>

/**
 * The two domain-scoped lists the site actually renders.
 *
 * Splitting them here, next to the data, is what keeps the top page and
 * `/works` from ever disagreeing about where a piece belongs: the top page's
 * MAIN group renders `aiProjects` (plus the case studies), `/works` renders
 * `webProjects`, and a project moves between the two surfaces by changing one
 * field — its `group` — and nothing else.
 */
export const aiProjects = archiveProjects.filter(
  (project) => CATEGORY_DOMAIN[project.group] === 'AI & Automation',
)

/** `/works` is the Web production gallery, and this is everything it shows. */
export const webProjects = archiveProjects.filter(
  (project) => CATEGORY_DOMAIN[project.group] === 'Web Production',
)

/** The filter tabs offered on `/works`, in the existing category order. */
export const webCategories = categoriesByDomain['Web Production']

/** Counted, never typed in: every "○件" on a web surface reads this. */
export const webProjectCount = webProjects.length
